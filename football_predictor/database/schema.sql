-- Spusť v Supabase SQL Editoru. Pouze serverová služba smí zapisovat.
-- Migrace navazuje na stávající tabulky matches a predictions.
create table if not exists matches (
 id bigint generated by default as identity primary key,
 kickoff_at timestamptz,
 home_team text not null,
 away_team text not null,
 home_goals integer,
 away_goals integer,
 created_at timestamptz not null default now()
);
alter table matches alter column kickoff_at drop not null;
alter table matches add column if not exists match_date date;
alter table matches add column if not exists source_match_key text;
alter table matches add column if not exists source text;
alter table matches add column if not exists season text;
create unique index if not exists idx_matches_source_key on matches(source_match_key);

create table if not exists predictions (
 id bigint generated by default as identity primary key,
 match_id bigint not null references matches(id) on delete cascade,
 model_version text not null,
 predicted_at timestamptz not null default now(),
 home_xg double precision,
 away_xg double precision,
 p_home double precision not null,
 p_draw double precision not null,
 p_away double precision not null,
 actual_outcome text,
 brier double precision,
 log_loss double precision
);
alter table predictions add column if not exists prediction_kind text not null default 'retrospective_backtest';
create unique index if not exists idx_predictions_version_kind on predictions(match_id, model_version, prediction_kind);
create index if not exists idx_matches_date on matches(match_date);
create index if not exists idx_predictions_match on predictions(match_id);
alter table matches enable row level security;
alter table predictions enable row level security;
