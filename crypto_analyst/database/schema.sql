-- Crypto Radar V1: prepared PostgreSQL schema for a dedicated Supabase project.
-- Does not modify Football Radar V1.
-- Private by default: RLS enabled, no anon/authenticated policies.

create table if not exists public.crypto_candles (
    id bigint generated by default as identity primary key,
    source text not null default 'binance',
    symbol text not null,
    timeframe text not null,
    open_time timestamptz not null,
    close_time timestamptz not null,
    open numeric(30, 12) not null check (open > 0),
    high numeric(30, 12) not null check (high > 0),
    low numeric(30, 12) not null check (low > 0),
    close numeric(30, 12) not null check (close > 0),
    volume numeric(38, 12) not null check (volume >= 0),
    quote_volume numeric(38, 12),
    trade_count bigint,
    fetched_at timestamptz not null default now(),
    constraint crypto_candles_price_range
       check (high >= greatest(open, low, close)
          and low <= least(open, high, close)),
    constraint crypto_candles_time_range check (close_time >= open_time),
    constraint crypto_candles_key unique (source, symbol, timeframe, open_time)
);

create table if not exists public.crypto_analysis_reports (
    id bigint generated by default as identity primary key,
    symbol text not null,
    timeframe text not null,
    candle_open_time timestamptz not null,
    model_version text not null,
    analyzed_at timestamptz not null default now(),
    last_close numeric(30, 12) not null check (last_close > 0),
    market_regime text not null,
    indicators jsonb not null default '{}'::jsonb,
    market_levels jsonb not null default '{}'::jsonb,
    analysis_notes jsonb not null default '[]'::jsonb,
    constraint crypto_analysis_reports_key
        unique (symbol, timeframe, candle_open_time, model_version)
);

create table if not exists public.crypto_ingestion_runs (
    id bigint generated by default as identity primary key,
    source text not null,
    symbol text not null,
    timeframe text not null,
    started_at timestamptz not null default now(),
    finished_at timestamptz,
    rows_written integer not null default 0,
    status text not null check (status in ('running','ok','error')),
    error_message text
);

create index if not exists idx_crypto_candles_lookup
    on public.crypto_candles (symbol, timeframe, open_time desc);
create index if not exists idx_crypto_reports_lookup
    on public.crypto_analysis_reports (symbol, timeframe, analyzed_at desc);

alter table public.crypto_candles enable row level security;
alter table public.crypto_analysis_reports enable row level security;
alter table public.crypto_ingestion_runs enable row level security;

-- No public RLS policies: ordinary browser clients cannot read or write rows.
-- Use trusted server-side connections for ingestion, never expose secret keys.
